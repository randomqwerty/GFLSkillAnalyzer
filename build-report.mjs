// Run every check on every unit and write the findings as one Markdown file (Node 18+).
//   node build-report.mjs [--data <folder or URL>] [--out <file.md>] [--kinds gun,enemy,sangvis] [--level1 10] [--level2 10] [--all]
// --data defaults to the GFLData repository on GitHub; a local folder must have the same layout
// (stc/*.json, text/table/*.json). Without --all only likely bugs and checks are listed.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadData, analyzeUnit, DEFAULT_BASE, CATEGORIES, UNIT_KINDS } from './analyzer.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const args = {};
for (let i = 0; i < argv.length; i++) if (argv[i].startsWith('--')) args[argv[i].slice(2)] = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true;
const base = typeof args.data === 'string' ? args.data : DEFAULT_BASE;
const out = path.resolve(typeof args.out === 'string' ? args.out : path.join(here, 'findings.md'));
const levels = { skill1: Number(args.level1 ?? 10), skill2: Number(args.level2 ?? 10) };
const kinds = String(typeof args.kinds === 'string' ? args.kinds : 'gun,enemy,sangvis').split(',').filter((k) => UNIT_KINDS[k]);

const isUrl = /^https?:/.test(base);
const fetchJson = isUrl ? undefined : async (p) => JSON.parse((await readFile(p, 'utf8')).replace(/^﻿/, ''));
const glossary = JSON.parse(await readFile(path.join(here, 'glossary-en.json'), 'utf8'));
const data = await loadData(isUrl ? base : path.resolve(base), { glossary, fetchJson, onProgress: (d, n, t) => process.stderr.write(`\rloading ${d}/${n} ${t}            `) });
process.stderr.write('\n');

const SEV = { bug: 'Likely bugs', warn: 'Checks', info: 'Notes' };
const keep = args.all ? ['bug', 'warn', 'info'] : ['bug', 'warn'];
const md = (s) => String(s).replace(/<\/?b>/g, '**').replace(/<\/?code>/g, '`').replace(/<[^>]+>/g, '')
  .replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&').replace(/\|/g, '\\|');
const rows = [];
for (const kind of kinds) {
  for (const g of data.units(kind)) {
    let a;
    try { a = analyzeUnit(data, kind, g.id, { levels }); } catch (e) { rows.push({ kind, id: g.id, name: data.unitName(kind, g), sev: 'bug', cat: 'other', text: `analyzer failed: ${e.message}` }); continue; }
    for (const n of a.notes) if (keep.includes(n.sev)) rows.push({ kind, id: g.id, name: a.name, sev: n.sev, cat: n.cat ?? 'other', text: n.text });
  }
}
const PLURAL = { gun: 'Dolls', enemy: 'Enemies', sangvis: 'Coalition units' };
const lines = ['# Skill findings', '',
  `Generated by \`tools/skill-analyzer/build-report.mjs\` at skill levels ${levels.skill1}/${levels.skill2} for ${kinds.map((k) => PLURAL[k].toLowerCase()).join(', ')}. Open a unit in the analyzer to see the skill in full.`, ''];
for (const kind of kinds) {
  const rk = rows.filter((x) => x.kind === kind);
  lines.push(`## ${PLURAL[kind]}`, '');
  for (const sev of keep) {
    const r = rk.filter((x) => x.sev === sev);
    lines.push(`### ${SEV[sev]} (${r.length})`, '');
    for (const [cat, label] of Object.entries({ ...CATEGORIES, other: 'Other' })) {
      const rc = r.filter((x) => x.cat === cat);
      if (!rc.length) continue;
      lines.push(`#### ${label} (${rc.length})`, '', '| Unit | Finding |', '|---|---|');
      for (const x of rc.sort((a, b) => a.id - b.id)) lines.push(`| ${md(x.name)} (#${x.id}) | ${md(x.text)} |`);
      lines.push('');
    }
  }
}
await writeFile(out, lines.join('\n'), 'utf8');
console.log(kinds.map((k) => `${k}: ${keep.map((s) => `${rows.filter((x) => x.kind === k && x.sev === s).length} ${s}`).join(', ')}`).join('; ') + ` → ${out}`);
